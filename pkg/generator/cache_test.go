func TestIsCachedNinjaFresh(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "bp2ninja_cache_test_*")
	if err != nil {
		t.Fatalf("Failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tempDir)

	subDir := filepath.Join(tempDir, "subproject")
	if err := os.MkdirAll(subDir, 0755); err != nil {
		t.Fatalf("Failed to create subDir: %v", err)
	}

	// 1. No build.ninja
	fresh, err := IsCachedNinjaFresh(subDir)
	if err != nil {
		t.Fatalf("Unexpected error for missing build.ninja: %v", err)
	}
	if fresh {
		t.Errorf("Expected fresh=false for missing build.ninja")
	}

	// 2. build.ninja exists but lacks bp2ninja signature header
	ninjaPath := filepath.Join(subDir, "build.ninja")
	if err := os.WriteFile(ninjaPath, []byte("# Generated by custom tool\nrule cp\n"), 0644); err != nil {
		t.Fatalf("Failed to write dummy build.ninja: %v", err)
	}
	fresh, err = IsCachedNinjaFresh(subDir)
	if err != nil || fresh {
		t.Errorf("Expected fresh=false for non-bp2ninja build.ninja, got fresh=%v, err=%v", fresh, err)
	}

	// 3. Valid bp2ninja header and older Android.bp
	bpPath := filepath.Join(subDir, "Android.bp")
	pastTime := time.Now().Add(-10 * time.Minute)
	if err := os.WriteFile(bpPath, []byte("cc_library { name: \"test_lib\" }\n"), 0644); err != nil {
		t.Fatalf("Failed to write Android.bp: %v", err)
	}
	_ = os.Chtimes(bpPath, pastTime, pastTime)

	ninjaContent := "# Generated by bp2ninja (Standalone Android.bp to Ninja Converter)\nninja_required_version = 1.7.0\n"
	if err := os.WriteFile(ninjaPath, []byte(ninjaContent), 0644); err != nil {
		t.Fatalf("Failed to write valid build.ninja: %v", err)
	}
	recentTime := time.Now().Add(-1 * time.Minute)
	_ = os.Chtimes(ninjaPath, recentTime, recentTime)

	fresh, err = IsCachedNinjaFresh(subDir)
	if err != nil || !fresh {
		t.Fatalf("Expected fresh=true for newer build.ninja, got fresh=%v, err=%v", fresh, err)
	}

	// 4. Modifying Android.bp makes cache stale
	futureTime := time.Now().Add(5 * time.Minute)
	_ = os.Chtimes(bpPath, futureTime, futureTime)

	fresh, err = IsCachedNinjaFresh(subDir)
	if err != nil || fresh {
		t.Errorf("Expected fresh=false when Android.bp is newer than build.ninja, got fresh=%v", fresh)
	}

	// 5. Modifying nested subdirectory Android.bp makes cache stale
	nestedDir := filepath.Join(subDir, "nested")
	if err := os.MkdirAll(nestedDir, 0755); err != nil {
		t.Fatalf("Failed to create nested dir: %v", err)
	}
	nestedBp := filepath.Join(nestedDir, "Android.bp")
	if err := os.WriteFile(nestedBp, []byte("// nested bp\n"), 0644); err != nil {
		t.Fatalf("Failed to write nested Android.bp: %v", err)
	}
	_ = os.Chtimes(bpPath, pastTime, pastTime)
	_ = os.Chtimes(ninjaPath, recentTime, recentTime)
	_ = os.Chtimes(nestedBp, futureTime, futureTime)

	fresh, err = IsCachedNinjaFresh(subDir)
	if err != nil || fresh {
		t.Errorf("Expected fresh=false when nested Android.bp is newer, got fresh=%v", fresh)
	}
}

func TestParseAndRebaseCachedNinja(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "bp2ninja_rebase_test_*")
	if err != nil {
		t.Fatalf("Failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tempDir)

	subDir := filepath.Join(tempDir, "subproject")
	srcDir := filepath.Join(subDir, "src")
	if err := os.MkdirAll(srcDir, 0755); err != nil {
		t.Fatalf("Failed to create src dir: %v", err)
	}

	srcFile := filepath.Join(srcDir, "lib.cpp")
	if err := os.WriteFile(srcFile, []byte("int test() { return 42; }\n"), 0644); err != nil {
		t.Fatalf("Failed to write src file: %v", err)
	}

	ninjaContent := `# Generated by bp2ninja (Standalone Android.bp to Ninja Converter)
ninja_required_version = 1.7.0
builddir = out
top = .

# bp2ninja_module: sub_lib cc_library out/lib64/sub_lib.so

rule cxx_compile
  command = clang++ -c $in -o $out
  description = CXX $out

rule link_shared
  command = clang++ -shared -o $out $in
  description = LINK $out

build out/obj/sub_lib.o: cxx_compile src/lib.cpp
build out/lib64/sub_lib.so: link_shared out/obj/sub_lib.o

build out/lib64/missing_dep.so: phony

default out/lib64/sub_lib.so
`
	ninjaPath := filepath.Join(subDir, "build.ninja")
	if err := os.WriteFile(ninjaPath, []byte(ninjaContent), 0644); err != nil {
		t.Fatalf("Failed to write build.ninja: %v", err)
	}

	info, err := ParseAndRebaseCachedNinja(tempDir, subDir, "out")
	if err != nil {
		t.Fatalf("ParseAndRebaseCachedNinja failed: %v", err)
	}

	if info.SubDir != "subproject" {
		t.Errorf("Expected SubDir='subproject', got '%s'", info.SubDir)
	}

	outs, ok := info.ModuleOutputs["sub_lib"]
	if !ok || len(outs) == 0 || outs[0] != "out/lib64/sub_lib.so" {
		t.Errorf("Expected ModuleOutputs['sub_lib']=['out/lib64/sub_lib.so'], got: %v", outs)
	}

	if len(info.MissingDeps) != 1 || info.MissingDeps[0] != "out/lib64/missing_dep.so" {
		t.Errorf("Expected MissingDeps=['out/lib64/missing_dep.so'], got: %v", info.MissingDeps)
	}

	rebasedData, err := os.ReadFile(info.SubninjaPath)
	if err != nil {
		t.Fatalf("Failed to read adapted subninja: %v", err)
	}
	rebasedText := string(rebasedData)

	// Check that relative source was rebased to subproject/src/lib.cpp
	if !strings.Contains(rebasedText, "build out/obj/sub_lib.o: cxx_compile subproject/src/lib.cpp") {
		t.Errorf("Expected rebased source path 'subproject/src/lib.cpp', got:\n%s", rebasedText)
	}

	// Check that empty fallback phony was stripped
	if strings.Contains(rebasedText, "build out/lib64/missing_dep.so: phony") {
		t.Errorf("Expected empty fallback phony to be stripped, got:\n%s", rebasedText)
	}

	// Check that default directive was stripped
	if strings.Contains(rebasedText, "default ") {
		t.Errorf("Expected default directive to be stripped, got:\n%s", rebasedText)
	}
}

func TestGeneratorWithCachedSubninjaEndToEnd(t *testing.T) {
	tempDir, err := os.MkdirTemp("", "bp2ninja_endtoend_cache_*")
	if err != nil {
		t.Fatalf("Failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tempDir)

	subDir := filepath.Join(tempDir, "mysub")
	if err := os.MkdirAll(subDir, 0755); err != nil {
		t.Fatalf("Failed to create mysub dir: %v", err)
	}

	subNinjaContent := `# Generated by bp2ninja (Standalone Android.bp to Ninja Converter)
ninja_required_version = 1.7.0
builddir = out
top = .

# bp2ninja_module: mysub_lib cc_library out/lib64/mysub_lib.so

rule dummy_touch
  command = touch $out
  description = TOUCH $out

build out/lib64/mysub_lib.so: dummy_touch
`
	if err := os.WriteFile(filepath.Join(subDir, "build.ninja"), []byte(subNinjaContent), 0644); err != nil {
		t.Fatalf("Failed to write sub build.ninja: %v", err)
	}

	info, err := ParseAndRebaseCachedNinja(tempDir, subDir, "out")
	if err != nil {
		t.Fatalf("ParseAndRebaseCachedNinja failed: %v", err)
	}

	// Create root module that links against mysub_lib
	rootSrc := filepath.Join(tempDir, "main.cpp")
	if err := os.WriteFile(rootSrc, []byte("int main() { return 0; }\n"), 0644); err != nil {
		t.Fatalf("Failed to write main.cpp: %v", err)
	}

	mod := &eval.EvaluatedModule{
		Type: "cc_binary",
		Name: "my_app",
		Dir:  "",
		Properties: map[string]interface{}{
			"srcs":        []interface{}{"main.cpp"},
			"shared_libs": []interface{}{"mysub_lib"},
		},
	}

	opts := DefaultOptions(tempDir, "out")
	opts.CachedSubninjas = []*CachedNinjaInfo{info}

	rootNinjaPath := filepath.Join(tempDir, "build.ninja")
	f, err := os.Create(rootNinjaPath)
	if err != nil {
		t.Fatalf("Failed to create root build.ninja: %v", err)
	}
	nw := ninja.NewWriter(f)
	gen := New(opts, nw, nil)

	if err := gen.Generate([]*eval.EvaluatedModule{mod}); err != nil {
		f.Close()
		t.Fatalf("Generate failed: %v", err)
	}
	f.Close()

	rootNinjaBytes, err := os.ReadFile(rootNinjaPath)
	if err != nil {
		t.Fatalf("Failed to read root build.ninja: %v", err)
	}
	rootNinjaText := string(rootNinjaBytes)

	// Verify subninja directive was written
	if !strings.Contains(rootNinjaText, "subninja out/.cache/mysub/build.ninja") {
		t.Errorf("Expected subninja directive in root build.ninja, got:\n%s", rootNinjaText)
	}

	// Verify my_app linked against out/lib64/mysub_lib.so
	if !strings.Contains(rootNinjaText, "out/lib64/mysub_lib.so") {
		t.Errorf("Expected my_app to reference out/lib64/mysub_lib.so, got:\n%s", rootNinjaText)
	}

	// If ninja is installed on the host, run a dry-run check
	if ninjaBin, err := exec.LookPath("ninja"); err == nil && ninjaBin != "" {
		cmd := exec.Command(ninjaBin, "-C", tempDir, "-f", rootNinjaPath, "-n")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("ninja dry-run failed: %v\nOutput: %s", err, string(out))
		}
		if !strings.Contains(string(out), "out/lib64/mysub_lib.so") {
			t.Errorf("ninja output did not mention mysub_lib.so: %s", string(out))
		}
	}
}
