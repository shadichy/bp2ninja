package generator

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// CachedNinjaInfo contains parsed and rebased metadata from a cached build.ninja file.
type CachedNinjaInfo struct {
	SubDir        string              // Relative path from rootDir, e.g. "lineage-sdk"
	NinjaPath     string              // Path to original build.ninja
	SubninjaPath  string              // Path to subninja file to include (e.g. in out/.cache)
	ModuleOutputs map[string][]string // Module name -> list of output files
	TaggedOutputs map[string][]string // Tagged output name (e.g. "foo:.aapt.srcjar") -> output files
	AllTargets    []string            // All targets generated by build statements
	MissingDeps   []string            // Fallback targets referenced by empty phony rules
}

// ToolMtimeCheckEnabled controls whether binary mtime invalidation is active.
var ToolMtimeCheckEnabled = true

// IsCachedNinjaFresh checks whether subDir contains a valid and fresh build.ninja
// generated by bp2ninja. A cache is considered fresh if:
// 1. build.ninja exists and contains the bp2ninja signature header.
// 2. build.ninja was generated by the matching bp2ninja version (# bp2ninja_version: <Version>).
// 3. The running bp2ninja executable is not newer than build.ninja.
// 4. Its modification timestamp is newer than or equal to all *.bp manifest files within subDir.
func IsCachedNinjaFresh(subDir string) (bool, error) {
	ninjaPath := filepath.Join(subDir, "build.ninja")
	fi, err := os.Stat(ninjaPath)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	if fi.IsDir() {
		return false, nil
	}

	// Verify header signature and version (within first 2048 bytes)
	f, err := os.Open(ninjaPath)
	if err != nil {
		return false, err
	}
	buf := make([]byte, 2048)
	n, _ := f.Read(buf)
	f.Close()
	header := string(buf[:n])
	if !strings.Contains(header, "Generated by bp2ninja") {
		return false, nil
	}

	// Verify tool version: must match current bp2ninja version
	expectedVerTag := "# bp2ninja_version: " + Version
	if !strings.Contains(header, expectedVerTag) {
		return false, nil
	}

	cacheTime := fi.ModTime()

	// Invalidate if the bp2ninja executable itself has been recompiled or updated
	if ToolMtimeCheckEnabled {
		if execPath, err := os.Executable(); err == nil && execPath != "" {
			// Skip check in unit test runners (e.g. go test temp binary)
			if !strings.HasSuffix(execPath, ".test") && !strings.Contains(execPath, "/go-build") {
				if execFi, err := os.Stat(execPath); err == nil {
					if execFi.ModTime().After(cacheTime.Add(100 * time.Millisecond)) {
						return false, nil
					}
				}
			}
		}
	}

	// Verify freshness against any *.bp files in the subtree
	stale := false
	err = filepath.Walk(subDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return nil
		}
		name := info.Name()
		if info.IsDir() {
			if path != subDir {
				if strings.HasPrefix(name, ".") || name == "out" || name == "node_modules" {
					return filepath.SkipDir
				}
			}
			return nil
		}
		if strings.HasSuffix(name, ".bp") {
			// If any Blueprint manifest is newer than the cached build.ninja, cache is stale
			if info.ModTime().After(cacheTime.Add(100 * time.Millisecond)) {
				stale = true
				return filepath.SkipAll
			}
		}
		return nil
	})
	if err != nil && err != filepath.SkipAll {
		return false, err
	}

	return !stale, nil
}

// ParseAndRebaseCachedNinja reads a cached build.ninja from subDir, extracts its module
// outputs, rebases relative input paths so they resolve properly from rootDir, strips
// redundant empty phony fallback rules and default statements, and writes out an adapted
// subninja file into outDir/.cache/<relDir>/build.ninja.
func ParseAndRebaseCachedNinja(rootDir, subDir, outDir string) (*CachedNinjaInfo, error) {
	ninjaPath := filepath.Join(subDir, "build.ninja")
	content, err := os.ReadFile(ninjaPath)
	if err != nil {
		return nil, fmt.Errorf("reading cached ninja %s: %w", ninjaPath, err)
	}

	relDir, err := filepath.Rel(rootDir, subDir)
	if err != nil || relDir == "." {
		relDir = ""
	}

	if outDir == "" {
		outDir = "out"
	}

	info := &CachedNinjaInfo{
		SubDir:        relDir,
		NinjaPath:     ninjaPath,
		ModuleOutputs: make(map[string][]string),
		TaggedOutputs: make(map[string][]string),
	}

	rebaseToken := func(p string) string {
		p = strings.TrimSpace(p)
		if p == "" || p == "|" || p == "||" || strings.HasPrefix(p, "$") || strings.HasPrefix(p, "-") || filepath.IsAbs(p) {
			return p
		}
		if p == outDir || strings.HasPrefix(p, outDir+"/") {
			return p
		}
		if relDir != "" && strings.HasPrefix(p, relDir+"/") {
			return p
		}
		// If path exists relative to rootDir, keep as-is
		if _, err := os.Stat(filepath.Join(rootDir, p)); err == nil {
			return p
		}
		// If path exists relative to subDir, rebase to relDir/p
		if relDir != "" {
			return filepath.Clean(filepath.Join(relDir, p))
		}
		return p
	}

	rebaseImportFlag := func(flag string) string {
		if strings.HasPrefix(flag, "-I") {
			inc := flag[2:]
			if inc == "." || inc == "" {
				if relDir != "" {
					return "-I" + relDir
				}
				return "-I."
			}
			return "-I" + rebaseToken(inc)
		}
		if strings.HasPrefix(flag, "-p") {
			p := flag[2:]
			return "-p" + rebaseToken(p)
		}
		return flag
	}

	scanner := bufio.NewScanner(bytes.NewReader(content))
	buf := make([]byte, 1024*1024)
	scanner.Buffer(buf, 64*1024*1024)
	var outLines []string

	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)

		// 1. Explicit metadata emitted by bp2ninja:
		// # bp2ninja_module: <name> <type> <outputs...>
		if strings.HasPrefix(trimmed, "# bp2ninja_module:") {
			parts := strings.Fields(trimmed)
			if len(parts) >= 3 {
				modName := parts[1]
				outs := parts[3:]
				var rebasedOuts []string
				for _, o := range outs {
					rebasedOuts = append(rebasedOuts, rebaseToken(o))
				}
				info.ModuleOutputs[modName] = rebasedOuts
			}
			outLines = append(outLines, line)
			continue
		}

		// 2. Build statements:
		// build <out1> <out2>: <rule> <in1> <in2> | <order1> <order2>
		if strings.HasPrefix(line, "build ") {
			colonIdx := strings.Index(line, ":")
			if colonIdx == -1 {
				outLines = append(outLines, line)
				continue
			}

			targetPart := strings.TrimSpace(line[6:colonIdx])
			rest := strings.TrimSpace(line[colonIdx+1:])

			ruleAndInputs := strings.Fields(rest)
			if len(ruleAndInputs) == 0 {
				outLines = append(outLines, line)
				continue
			}
			ruleName := ruleAndInputs[0]
			inputsPart := ""
			if len(ruleAndInputs) > 1 {
				inputsPart = strings.TrimSpace(rest[len(ruleName):])
			}

			// Filter out empty fallback phony rules (build target: phony) to prevent duplicate rule collisions
			if ruleName == "phony" && inputsPart == "" {
				for _, t := range strings.Fields(targetPart) {
					info.MissingDeps = append(info.MissingDeps, t)
				}
				continue
			}

			var targetList, implicitTargetList []string
			if pipeIdx := strings.Index(targetPart, "|"); pipeIdx != -1 {
				targetList = strings.Fields(targetPart[:pipeIdx])
				implicitTargetList = strings.Fields(targetPart[pipeIdx+1:])
			} else {
				targetList = strings.Fields(targetPart)
			}
			var rebasedTargets, rebasedImplicitTargets []string
			for _, t := range targetList {
				rebased := rebaseToken(t)
				rebasedTargets = append(rebasedTargets, rebased)
				info.AllTargets = append(info.AllTargets, rebased)
				// Infer module names and tagged outputs from canonical build targets if not explicitly set
				inferModuleOutput(info, rebased, ruleName, inputsPart)
			}
			for _, t := range implicitTargetList {
				rebased := rebaseToken(t)
				rebasedImplicitTargets = append(rebasedImplicitTargets, rebased)
				info.AllTargets = append(info.AllTargets, rebased)
			}
			rebasedTargetPart := strings.Join(rebasedTargets, " ")
			if len(rebasedImplicitTargets) > 0 {
				rebasedTargetPart += " | " + strings.Join(rebasedImplicitTargets, " ")
			}

			// Rebase inputs, implicit dependencies, and order-only dependencies
			var explicitPart, implicitPart, orderOnlyPart string
			if dbarIdx := strings.Index(inputsPart, "||"); dbarIdx != -1 {
				orderOnlyPart = strings.TrimSpace(inputsPart[dbarIdx+2:])
				inputsPart = strings.TrimSpace(inputsPart[:dbarIdx])
			}
			if barIdx := strings.Index(inputsPart, "|"); barIdx != -1 {
				implicitPart = strings.TrimSpace(inputsPart[barIdx+1:])
				explicitPart = strings.TrimSpace(inputsPart[:barIdx])
			} else {
				explicitPart = strings.TrimSpace(inputsPart)
			}

			var inTokens, implicitTokens, orderTokens []string
			for _, tok := range strings.Fields(explicitPart) {
				inTokens = append(inTokens, rebaseToken(tok))
			}
			for _, tok := range strings.Fields(implicitPart) {
				implicitTokens = append(implicitTokens, rebaseToken(tok))
			}
			for _, tok := range strings.Fields(orderOnlyPart) {
				orderTokens = append(orderTokens, rebaseToken(tok))
			}

			rebasedBuild := fmt.Sprintf("build %s: %s %s", rebasedTargetPart, ruleName, strings.Join(inTokens, " "))
			if len(implicitTokens) > 0 {
				rebasedBuild += " | " + strings.Join(implicitTokens, " ")
			}
			if len(orderTokens) > 0 {
				rebasedBuild += " || " + strings.Join(orderTokens, " ")
			}
			outLines = append(outLines, rebasedBuild)
			continue
		}

		// 3. Statement variable overrides:
		if strings.HasPrefix(line, "  rspcontent = ") {
			tokens := strings.Fields(line[15:])
			var rebased []string
			for _, t := range tokens {
				rebased = append(rebased, rebaseToken(t))
			}
			outLines = append(outLines, "  rspcontent = "+strings.Join(rebased, " "))
			continue
		}

		if strings.HasPrefix(line, "  manifest = ") {
			p := strings.TrimSpace(line[13:])
			outLines = append(outLines, "  manifest = "+rebaseToken(p))
			continue
		}

		if strings.HasPrefix(line, "  imports = ") {
			flags := strings.Fields(line[12:])
			var rebased []string
			for _, f := range flags {
				rebased = append(rebased, rebaseImportFlag(f))
			}
			outLines = append(outLines, "  imports = "+strings.Join(rebased, " "))
			continue
		}

		if strings.HasPrefix(line, "  includes = ") {
			flags := strings.Fields(line[13:])
			var rebased []string
			for _, f := range flags {
				rebased = append(rebased, rebaseImportFlag(f))
			}
			outLines = append(outLines, "  includes = "+strings.Join(rebased, " "))
			continue
		}

		if strings.HasPrefix(line, "  ldflags = ") {
			flags := strings.Fields(line[12:])
			var rebased []string
			for _, f := range flags {
				if strings.HasPrefix(f, "-L") {
					rebased = append(rebased, "-L"+rebaseToken(f[2:]))
				} else if strings.HasPrefix(f, "-B") {
					rebased = append(rebased, "-B"+rebaseToken(f[2:]))
				} else if strings.HasPrefix(f, "-Wl,--version-script=") {
					rebased = append(rebased, "-Wl,--version-script="+rebaseToken(f[22:]))
				} else {
					rebased = append(rebased, f)
				}
			}
			outLines = append(outLines, "  ldflags = "+strings.Join(rebased, " "))
			continue
		}

		if strings.HasPrefix(line, "  cflags = ") {
			flags := strings.Fields(line[11:])
			var rebased []string
			for _, f := range flags {
				if strings.HasPrefix(f, "-I") {
					rebased = append(rebased, rebaseImportFlag(f))
				} else {
					rebased = append(rebased, f)
				}
			}
			outLines = append(outLines, "  cflags = "+strings.Join(rebased, " "))
			continue
		}

		if strings.HasPrefix(line, "  protoc_args = ") {
			args := strings.Fields(line[16:])
			var rebased []string
			for _, arg := range args {
				if strings.HasPrefix(arg, "--cpp_out=") {
					rebased = append(rebased, "--cpp_out="+rebaseToken(arg[10:]))
				} else if strings.HasPrefix(arg, "--java_out=") {
					rebased = append(rebased, "--java_out="+rebaseToken(arg[11:]))
				} else if strings.HasPrefix(arg, "--python_out=") {
					rebased = append(rebased, "--python_out="+rebaseToken(arg[13:]))
				} else if strings.HasPrefix(arg, "-I") {
					rebased = append(rebased, rebaseImportFlag(arg))
				} else {
					rebased = append(rebased, rebaseToken(arg))
				}
			}
			outLines = append(outLines, "  protoc_args = "+strings.Join(rebased, " "))
			continue
		}

		// 4. Default targets:
		// Subninja default targets should not override root default targets
		if strings.HasPrefix(line, "default ") {
			continue
		}

		// All other lines (rules, variables, comments) are preserved
		outLines = append(outLines, line)
	}

	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("scanning cached ninja %s: %w", ninjaPath, err)
	}

	// Write adapted subninja into outDir/.cache/<relDir>/build.ninja
	cacheSubninjaDir := filepath.Join(rootDir, outDir, ".cache", relDir)
	if err := os.MkdirAll(cacheSubninjaDir, 0755); err != nil {
		return nil, fmt.Errorf("creating cache dir %s: %w", cacheSubninjaDir, err)
	}

	cacheSubninjaPath := filepath.Join(cacheSubninjaDir, "build.ninja")
	if err := os.WriteFile(cacheSubninjaPath, []byte(strings.Join(outLines, "\n")+"\n"), 0644); err != nil {
		return nil, fmt.Errorf("writing adapted subninja %s: %w", cacheSubninjaPath, err)
	}

	info.SubninjaPath = cacheSubninjaPath
	return info, nil
}

// inferModuleOutput registers targets into ModuleOutputs and TaggedOutputs using canonical
// bp2ninja artifact path conventions when explicit bp2ninja_module comments are absent.
func inferModuleOutput(info *CachedNinjaInfo, target, ruleName, inputsPart string) {
	// Rule: build <alias>: phony <target>
	if ruleName == "phony" && inputsPart != "" && !strings.Contains(target, "/") {
		inFields := strings.Fields(inputsPart)
		if len(inFields) > 0 {
			info.ModuleOutputs[target] = []string{inFields[0]}
		}
		return
	}

	// out/lib64/<name>.jar or out/lib/<name>.jar
	if (strings.HasPrefix(target, "out/lib64/") || strings.HasPrefix(target, "out/lib/")) && strings.HasSuffix(target, ".jar") {
		base := filepath.Base(target)
		modName := strings.TrimSuffix(base, ".jar")
		if !contains(info.ModuleOutputs[modName], target) {
			info.ModuleOutputs[modName] = append(info.ModuleOutputs[modName], target)
		}
		return
	}

	// out/lib64/<name>.so or out/lib/<name>.so
	if (strings.HasPrefix(target, "out/lib64/") || strings.HasPrefix(target, "out/lib/")) && strings.HasSuffix(target, ".so") {
		base := filepath.Base(target)
		modName := strings.TrimSuffix(base, ".so")
		if !contains(info.ModuleOutputs[modName], target) {
			info.ModuleOutputs[modName] = append(info.ModuleOutputs[modName], target)
		}
		return
	}

	// out/lib64/<name>.a or out/lib/<name>.a
	if (strings.HasPrefix(target, "out/lib64/") || strings.HasPrefix(target, "out/lib/")) && strings.HasSuffix(target, ".a") {
		base := filepath.Base(target)
		modName := strings.TrimSuffix(base, ".a")
		if !contains(info.ModuleOutputs[modName], target) {
			info.ModuleOutputs[modName] = append(info.ModuleOutputs[modName], target)
		}
		return
	}

	// out/bin/<name>.apk
	if strings.HasPrefix(target, "out/bin/") && strings.HasSuffix(target, ".apk") {
		base := filepath.Base(target)
		modName := strings.TrimSuffix(base, ".apk")
		if !contains(info.ModuleOutputs[modName], target) {
			info.ModuleOutputs[modName] = append(info.ModuleOutputs[modName], target)
		}
		return
	}

	// out/bin/<name>
	if strings.HasPrefix(target, "out/bin/") && !strings.Contains(filepath.Base(target), ".") {
		modName := filepath.Base(target)
		if !contains(info.ModuleOutputs[modName], target) {
			info.ModuleOutputs[modName] = append(info.ModuleOutputs[modName], target)
		}
		return
	}

	// out/gen/<name>/<name>.srcjar
	if strings.Contains(target, "/gen/") && strings.HasSuffix(target, ".srcjar") {
		base := filepath.Base(target)
		modName := strings.TrimSuffix(base, ".srcjar")
		tag1 := modName + ":.aapt.srcjar"
		tag2 := modName + ":.srcjar"
		if !contains(info.TaggedOutputs[tag1], target) {
			info.TaggedOutputs[tag1] = append(info.TaggedOutputs[tag1], target)
		}
		if !contains(info.TaggedOutputs[tag2], target) {
			info.TaggedOutputs[tag2] = append(info.TaggedOutputs[tag2], target)
		}
		return
	}
}

func contains(slice []string, val string) bool {
	for _, s := range slice {
		if s == val {
			return true
		}
	}
	return false
}
