var reHidlName = regexp.MustCompile(`^([a-zA-Z_][a-zA-Z0-9_]*(?:\.[a-zA-Z_][a-zA-Z0-9_]*)*)@([0-9]+)\.([0-9]+)$`)

// hidlInterfaceInfo encapsulates parsed HIDL interface metadata.
type hidlInterfaceInfo struct {
	Name            string // e.g. "android.hidl.base@1.0"
	Pkg             string // e.g. "android.hidl.base"
	Major           string // e.g. "1"
	Minor           string // e.g. "0"
	Version         string // e.g. "1.0"
	PkgDir          string // e.g. "android/hidl/base/1.0"
	SanitizedString string // e.g. "android.hidl.base-V1.0"
	SourcesName     string // e.g. "android.hidl.base@1.0_genc++"
	HeadersName     string // e.g. "android.hidl.base@1.0_genc++_headers"
	JavaName        string // e.g. "android.hidl.base-V1.0-java"
	JavaConstName   string // e.g. "android.hidl.base-V1.0-java-constants"
	Interfaces      []string
	Types           []string
	Root            string
	GenJava         bool
	GenJavaConst    bool
}

// parseHidlInterfaceName parses a HIDL fully qualified interface name (e.g. android.hidl.base@1.0).
func parseHidlInterfaceName(name string) (*hidlInterfaceInfo, error) {
	match := reHidlName.FindStringSubmatch(name)
	if match == nil {
		return nil, fmt.Errorf("invalid HIDL interface name: %q (expected <package>@<major>.<minor>)", name)
	}
	pkg := match[1]
	major := match[2]
	minor := match[3]
	version := major + "." + minor
	pkgDir := filepath.Join(strings.ReplaceAll(pkg, ".", "/"), version)
	sanitized := pkg + "-V" + version

	return &hidlInterfaceInfo{
		Name:            name,
		Pkg:             pkg,
		Major:           major,
		Minor:           minor,
		Version:         version,
		PkgDir:          pkgDir,
		SanitizedString: sanitized,
		SourcesName:     name + "_genc++",
		HeadersName:     name + "_genc++_headers",
		JavaName:        sanitized + "-java",
		JavaConstName:   sanitized + "-java-constants",
	}, nil
}

// sanitizeHidlJavaName returns the canonical Java library module name for a HIDL interface.
func sanitizeHidlJavaName(name string) string {
	info, err := parseHidlInterfaceName(name)
	if err != nil {
		return name + "-java"
	}
	return info.JavaName
}

func (info *hidlInterfaceInfo) parseSources(srcs []string) {
	for _, s := range srcs {
		base := filepath.Base(s)
		if !strings.HasSuffix(base, ".hal") {
			continue
		}
		raw := strings.TrimSuffix(base, ".hal")
		if strings.HasPrefix(raw, "I") {
			info.Interfaces = append(info.Interfaces, strings.TrimPrefix(raw, "I"))
		} else {
			info.Types = append(info.Types, raw)
		}
	}
}

// calculateHidlCppOutputs returns the relative output paths generated by hidl-gen for C++ sources or headers.
func calculateHidlCppOutputs(info *hidlInterfaceInfo, genDir string, headersOnly bool) []string {
	var outs []string
	if headersOnly {
		for _, iface := range info.Interfaces {
			outs = append(outs,
				filepath.Join(genDir, info.PkgDir, "I"+iface+".h"),
				filepath.Join(genDir, info.PkgDir, "Bs"+iface+".h"),
				filepath.Join(genDir, info.PkgDir, "BnHw"+iface+".h"),
				filepath.Join(genDir, info.PkgDir, "BpHw"+iface+".h"),
				filepath.Join(genDir, info.PkgDir, "IHw"+iface+".h"),
			)
		}
		for _, t := range info.Types {
			outs = append(outs,
				filepath.Join(genDir, info.PkgDir, t+".h"),
				filepath.Join(genDir, info.PkgDir, "hw"+t+".h"),
			)
		}
	} else {
		for _, iface := range info.Interfaces {
			outs = append(outs, filepath.Join(genDir, info.PkgDir, iface+"All.cpp"))
		}
		for _, t := range info.Types {
			outs = append(outs, filepath.Join(genDir, info.PkgDir, t+".cpp"))
		}
	}
	return outs
}

// expandHidlInterfaces preprocesses modules before dependency sorting:
// 1. Collects hidl_package_root specifications.
// 2. Synthesizes <name>_genc++, <name>_genc++_headers, and <sanitized>-java modules for hidl_interface declarations.
func (g *Generator) expandHidlInterfaces(modules []*eval.EvaluatedModule) []*eval.EvaluatedModule {
	// First pass: register package roots
	for _, mod := range modules {
		if mod.Type == "hidl_package_root" {
			rootPath := mod.GetString("path")
			if rootPath == "" {
				if mod.Dir != "" && mod.Dir != "." {
					rootPath = mod.Dir
				} else {
					rootPath = "."
				}
			}
			g.hidlPackageRoots[mod.Name] = rootPath
		}
	}

	var result []*eval.EvaluatedModule
	for _, mod := range modules {
		if mod.Type != "hidl_interface" {
			result = append(result, mod)
			continue
		}

		info, err := parseHidlInterfaceName(mod.Name)
		if err != nil {
			result = append(result, mod)
			continue
		}

		srcs := mod.GetStringList("srcs")
		info.parseSources(srcs)
		info.Root = mod.GetString("root")
		info.GenJava = true
		if val, ok := mod.Properties["gen_java"]; ok {
			if b, ok := val.(bool); ok {
				info.GenJava = b
			}
		}
		info.GenJavaConst = mod.GetBool("gen_java_constants")

		rootOpt := g.resolveHidlRootOptions(mod, info.Root)

		// 1. Synthesize <name>_genc++ (C++ source generation)
		gencppMod := &eval.EvaluatedModule{
			Type: "hidl_gen_sources",
			Name: info.SourcesName,
			Dir:  mod.Dir,
			Properties: map[string]interface{}{
				"name":        info.SourcesName,
				"srcs":        mod.Properties["srcs"],
				"root":        info.Root,
				"root_option": rootOpt,
				"fq_name":     mod.Name,
			},
		}
		result = append(result, gencppMod)

		// 2. Synthesize <name>_genc++_headers (C++ header generation)
		genhdrMod := &eval.EvaluatedModule{
			Type: "hidl_gen_headers",
			Name: info.HeadersName,
			Dir:  mod.Dir,
			Properties: map[string]interface{}{
				"name":        info.HeadersName,
				"srcs":        mod.Properties["srcs"],
				"root":        info.Root,
				"root_option": rootOpt,
				"fq_name":     mod.Name,
			},
		}
		result = append(result, genhdrMod)

		// 3. Synthesize <sanitized>-java (Java interface library)
		if info.GenJava {
			javaMod := &eval.EvaluatedModule{
				Type: "hidl_java_library",
				Name: info.JavaName,
				Dir:  mod.Dir,
				Properties: map[string]interface{}{
					"name":        info.JavaName,
					"srcs":        mod.Properties["srcs"],
					"root":        info.Root,
					"root_option": rootOpt,
					"interfaces":  mod.Properties["interfaces"],
					"fq_name":     mod.Name,
				},
			}
			result = append(result, javaMod)
		}

		// 4. Synthesize <sanitized>-java-constants if requested
		if info.GenJavaConst {
			javaConstMod := &eval.EvaluatedModule{
				Type: "hidl_java_constants",
				Name: info.JavaConstName,
				Dir:  mod.Dir,
				Properties: map[string]interface{}{
					"name":        info.JavaConstName,
					"srcs":        mod.Properties["srcs"],
					"root":        info.Root,
					"root_option": rootOpt,
					"fq_name":     mod.Name,
				},
			}
			result = append(result, javaConstMod)
		}

		// 5. Update hidl_interface module to depend on _genc++ and _genc++_headers
		if mod.Properties == nil {
			mod.Properties = make(map[string]interface{})
		}
		mod.Properties["generated_sources"] = []interface{}{info.SourcesName}
		mod.Properties["generated_headers"] = []interface{}{info.HeadersName}
		mod.Properties["export_generated_headers"] = []interface{}{info.HeadersName}

		var sharedLibs []interface{}
		for _, iface := range mod.GetStringList("interfaces") {
			sharedLibs = append(sharedLibs, iface)
		}
		sharedLibs = append(sharedLibs, "libhidlbase", "liblog", "libutils", "libcutils")
		mod.Properties["shared_libs"] = sharedLibs

		var exportLibs []interface{}
		for _, iface := range mod.GetStringList("interfaces") {
			exportLibs = append(exportLibs, iface)
		}
		exportLibs = append(exportLibs, "libhidlbase", "libutils")
		mod.Properties["export_shared_lib_headers"] = exportLibs

		result = append(result, mod)
	}

	return result
}

// resolveHidlRootOptions calculates the -r <root>:<path> option for hidl-gen.
func (g *Generator) resolveHidlRootOptions(mod *eval.EvaluatedModule, root string) string {
	var opts []string
	seenRoots := make(map[string]bool)

	addRoot := func(r, p string) {
		if r == "" || seenRoots[r] {
			return
		}
		seenRoots[r] = true
		opts = append(opts, fmt.Sprintf("-r%s:%s", r, p))
	}

	// 1. Check module's own declared root
	if root != "" {
		if p, ok := g.hidlPackageRoots[root]; ok {
			addRoot(root, p)
		} else if mod != nil && mod.Dir != "" && mod.Dir != "." {
			// Infer root path by removing the package directory suffix from mod.Dir
			// e.g. mod.Dir = "transport/base/1.0", fqName = "android.hidl.base@1.0", root = "android.hidl"
			// suffix under root is "base/1.0" -> path is "transport"
			info, err := parseHidlInterfaceName(mod.Name)
			if err == nil {
				pkgSuffix := strings.TrimPrefix(info.Pkg, root)
				pkgSuffix = strings.TrimPrefix(pkgSuffix, ".")
				subDir := filepath.Join(strings.ReplaceAll(pkgSuffix, ".", "/"), info.Version)
				if strings.HasSuffix(mod.Dir, subDir) {
					inferred := strings.TrimSuffix(mod.Dir, subDir)
					inferred = strings.TrimSuffix(inferred, "/")
					if inferred == "" {
						inferred = "."
					}
					addRoot(root, inferred)
				}
			}
			if !seenRoots[root] {
				addRoot(root, mod.Dir)
			}
		} else {
			addRoot(root, ".")
		}
	}

	// 2. Include all other registered package roots
	for r, p := range g.hidlPackageRoots {
		addRoot(r, p)
	}

	return strings.Join(opts, " ")
}

func (g *Generator) collectHalSources(mod *eval.EvaluatedModule) []string {
	rawSrcs := mod.GetStringList("srcs")
	var halSrcs []string
	for _, s := range rawSrcs {
		srcPath := s
		if mod.Dir != "" && mod.Dir != "." && !filepath.IsAbs(s) {
			srcPath = filepath.Clean(filepath.Join(mod.Dir, s))
		}
		halSrcs = append(halSrcs, srcPath)
	}
	return halSrcs
}

// generateHidlGenSources emits the hidl-gen -L c++-sources codegen build edge.
func (g *Generator) generateHidlGenSources(mod *eval.EvaluatedModule) ([]string, error) {
	fqName := mod.GetString("fq_name")
	if fqName == "" {
		fqName = strings.TrimSuffix(mod.Name, "_genc++")
	}
	info, err := parseHidlInterfaceName(fqName)
	if err != nil {
		return nil, err
	}

	srcs := mod.GetStringList("srcs")
	info.parseSources(srcs)

	genDir := filepath.Join(g.opts.OutDir, "gen", mod.Name)
	outs := calculateHidlCppOutputs(info, genDir, false)

	halSrcs := g.collectHalSources(mod)
	rootOpt := mod.GetString("root_option")
	if rootOpt == "" {
		rootOpt = g.resolveHidlRootOptions(mod, mod.GetString("root"))
	}

	_ = g.nw.Build(ninja.BuildEdge{
		Outputs: outs,
		Rule:    "hidl_cpp_sources",
		Inputs:  halSrcs,
		Variables: map[string]string{
			"gen_dir": genDir,
			"options": rootOpt,
			"fq_name": fqName,
		},
	})

	return outs, nil
}

