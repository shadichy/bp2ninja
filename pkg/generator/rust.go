package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"bp2ninja/pkg/eval"
	"bp2ninja/pkg/ninja"
)

// generateRustModule handles Rust module compilation (rust_ffi, rust_library, rust_binary, rust_proc_macro)
// via Cargo manifest synthesis and the cargo_build ninja rule.
func (g *Generator) generateRustModule(mod *eval.EvaluatedModule) ([]string, error) {
	crateName := mod.GetString("crate_name")
	if crateName == "" {
		crateName = strings.TrimPrefix(mod.Name, "lib")
	}
	// Cargo crate names allow alphanumeric and underscores
	crateName = strings.ReplaceAll(crateName, "-", "_")

	edition := mod.GetString("edition")
	if edition == "" {
		edition = "2021"
	}

	version := mod.GetString("cargo_pkg_version")
	if version == "" {
		version = "0.1.0"
	}

	srcs := g.ResolveSrcs(mod)
	mainSrc := ""
	for _, s := range srcs {
		base := filepath.Base(s)
		if base == "lib.rs" || base == "main.rs" {
			mainSrc = s
			break
		}
	}
	if mainSrc == "" && len(srcs) > 0 {
		for _, s := range srcs {
			if strings.HasSuffix(s, ".rs") {
				mainSrc = s
				break
			}
		}
	}
	if mainSrc == "" {
		if strings.Contains(mod.Type, "binary") {
			mainSrc = "src/main.rs"
		} else {
			mainSrc = "src/lib.rs"
		}
		if mod.Dir != "" && mod.Dir != "." {
			mainSrc = filepath.Join(mod.Dir, mainSrc)
		}
	}

	isHost := mod.IsHostSupported() && (g.opts.IsHost || strings.Contains(mod.Type, "_host"))
	isBinary := mod.Type == "rust_binary" || mod.Type == "rust_binary_host"
	isProcMacro := mod.Type == "rust_proc_macro"

	var crateTypes []string
	switch mod.Type {
	case "rust_ffi":
		crateTypes = []string{"staticlib", "cdylib"}
	case "rust_ffi_static", "rust_ffi_host_static":
		crateTypes = []string{"staticlib"}
	case "rust_ffi_shared", "rust_ffi_host_shared":
		crateTypes = []string{"cdylib"}
	case "rust_library", "rust_library_host", "rust_library_rlib":
		crateTypes = []string{"rlib"}
	case "rust_library_dylib", "rust_library_host_dylib":
		crateTypes = []string{"dylib"}
	}

	// Target triple derivation
	triple := ""
	if !isHost {
		arch := g.opts.TargetArch
		if arch == "" {
			arch = "arm64"
		}
		switch arch {
		case "arm64":
			triple = "aarch64-linux-android"
		case "x86_64":
			triple = "x86_64-linux-android"
		case "arm":
			triple = "armv7-linux-androideabi"
		case "x86":
			triple = "i686-linux-android"
		case "riscv64":
			triple = "riscv64-linux-android"
		default:
			triple = "aarch64-linux-android"
		}
	}

	// Cargo manifest directory
	cargoDir := filepath.Join(g.opts.OutDir, "cargo", mod.Name)
	if g.opts.CargoOutDir != "" {
		cargoDir = filepath.Join(g.opts.CargoOutDir, mod.Name)
	}
	if err := os.MkdirAll(cargoDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create cargo directory %s: %w", cargoDir, err)
	}

	// Compute relative path to main source from cargoDir
	relMainSrc, err := filepath.Rel(cargoDir, mainSrc)
	if err != nil {
		relMainSrc = mainSrc
	}

	// Synthesize Cargo.toml
	manifestPath := filepath.Join(cargoDir, "Cargo.toml")
	var manifest strings.Builder
	manifest.WriteString("# Auto-generated by bp2ninja / bp2cargo. DO NOT EDIT.\n")
	manifest.WriteString("[package]\n")
	manifest.WriteString(fmt.Sprintf("name = %q\n", crateName))
	manifest.WriteString(fmt.Sprintf("version = %q\n", version))
	manifest.WriteString(fmt.Sprintf("edition = %q\n", edition))
	manifest.WriteString("\n")

	if isBinary {
		manifest.WriteString("[[bin]]\n")
		manifest.WriteString(fmt.Sprintf("name = %q\n", mod.Name))
		manifest.WriteString(fmt.Sprintf("path = %q\n", relMainSrc))
		manifest.WriteString("\n")
	} else {
		manifest.WriteString("[lib]\n")
		manifest.WriteString(fmt.Sprintf("name = %q\n", crateName))
		manifest.WriteString(fmt.Sprintf("path = %q\n", relMainSrc))
		if isProcMacro {
			manifest.WriteString("proc-macro = true\n")
		} else if len(crateTypes) > 0 {
			var formatted []string
			for _, ct := range crateTypes {
				formatted = append(formatted, fmt.Sprintf("%q", ct))
			}
			manifest.WriteString(fmt.Sprintf("crate-type = [%s]\n", strings.Join(formatted, ", ")))
		}
		manifest.WriteString("\n")
	}

	features := mod.GetStringList("features")
	if len(features) > 0 {
		manifest.WriteString("[features]\n")
		var fList []string
		for _, f := range features {
			fList = append(fList, fmt.Sprintf("%q", f))
		}
		manifest.WriteString(fmt.Sprintf("default = [%s]\n\n", strings.Join(fList, ", ")))
	}

	rustlibs := append(mod.GetStringList("rustlibs"), mod.GetStringList("rlibs")...)
	rustlibs = append(rustlibs, mod.GetStringList("proc_macros")...)
	if len(rustlibs) > 0 {
		manifest.WriteString("[dependencies]\n")
		for _, dep := range dedup(rustlibs) {
			depCrate := strings.TrimPrefix(dep, "lib")
			depCrate = strings.ReplaceAll(depCrate, "-", "_")
			depCargoDir := filepath.Join(g.opts.OutDir, "cargo", dep)
			if g.opts.CargoOutDir != "" {
				depCargoDir = filepath.Join(g.opts.CargoOutDir, dep)
			}
			if depMod, ok := g.moduleMap[dep]; ok && depMod.Dir != "" && depMod.Dir != "." {
				relPath, rErr := filepath.Rel(cargoDir, depMod.Dir)
				if rErr == nil {
					manifest.WriteString(fmt.Sprintf("%s = { path = %q }\n", depCrate, relPath))
					continue
				}
			}
			relPath, rErr := filepath.Rel(cargoDir, depCargoDir)
			if rErr == nil {
				manifest.WriteString(fmt.Sprintf("%s = { path = %q }\n", depCrate, relPath))
			} else {
				manifest.WriteString(fmt.Sprintf("%s = { version = \"*\" }\n", depCrate))
			}
		}
		manifest.WriteString("\n")
	}

	if err := os.WriteFile(manifestPath, []byte(manifest.String()), 0644); err != nil {
		return nil, fmt.Errorf("failed to write synthesized Cargo.toml to %s: %w", manifestPath, err)
	}

	// Determine output artifacts
	var allOutputs []string
	var copyCommands []string

	targetDir := filepath.Join(cargoDir, "target")
	artifactDir := filepath.Join(targetDir, "release")
	if !isHost && triple != "" {
		artifactDir = filepath.Join(targetDir, triple, "release")
	}

	cleanModName := strings.TrimPrefix(mod.Name, "lib")

	if isBinary {
		binTarget := filepath.Join(g.binDir(), mod.Name)
		allOutputs = append(allOutputs, binTarget)
		cargoBin := filepath.Join(artifactDir, mod.Name)
		copyCommands = append(copyCommands, fmt.Sprintf("mkdir -p %s && cp -f %s %s", g.binDir(), cargoBin, binTarget))
	}

	for _, ct := range crateTypes {
		switch ct {
		case "staticlib":
			staticTarget := filepath.Join(g.libDir(), "lib"+cleanModName+".a")
			allOutputs = append(allOutputs, staticTarget)
			cargoArchive := filepath.Join(artifactDir, "lib"+crateName+".a")
			cmd := fmt.Sprintf("mkdir -p %s && cp -f %s %s", g.libDir(), cargoArchive, staticTarget)
			if crateName != cleanModName {
				crateTarget := filepath.Join(g.libDir(), "lib"+crateName+".a")
				cmd += fmt.Sprintf(" && cp -f %s %s", cargoArchive, crateTarget)
				allOutputs = append(allOutputs, crateTarget)
			}
			copyCommands = append(copyCommands, cmd)
		case "cdylib", "dylib":
			sharedTarget := filepath.Join(g.libDir(), "lib"+cleanModName+".so")
			allOutputs = append(allOutputs, sharedTarget)
			cargoShared := filepath.Join(artifactDir, "lib"+crateName+".so")
			cmd := fmt.Sprintf("mkdir -p %s && cp -f %s %s", g.libDir(), cargoShared, sharedTarget)
			if crateName != cleanModName {
				crateTarget := filepath.Join(g.libDir(), "lib"+crateName+".so")
				cmd += fmt.Sprintf(" && cp -f %s %s", cargoShared, crateTarget)
				allOutputs = append(allOutputs, crateTarget)
			}
			copyCommands = append(copyCommands, cmd)
		case "rlib":
			rlibTarget := filepath.Join(g.libDir(), "lib"+cleanModName+".rlib")
			allOutputs = append(allOutputs, rlibTarget)
			cargoRlib := filepath.Join(artifactDir, "lib"+crateName+".rlib")
			copyCommands = append(copyCommands, fmt.Sprintf("mkdir -p %s && cp -f %s %s", g.libDir(), cargoRlib, rlibTarget))
		}
	}

	if isProcMacro {
		macroTarget := filepath.Join(g.libDir(), "lib"+cleanModName+".so")
		allOutputs = append(allOutputs, macroTarget)
		cargoShared := filepath.Join(artifactDir, "lib"+crateName+".so")
		copyCommands = append(copyCommands, fmt.Sprintf("mkdir -p %s && cp -f %s %s", g.libDir(), cargoShared, macroTarget))
	}

	allOutputs = dedup(allOutputs)

	// Build command execution string
	var cmdParts []string
	if !isHost && triple != "" {
		upperTriple := strings.ToUpper(strings.ReplaceAll(triple, "-", "_"))
		cmdParts = append(cmdParts, fmt.Sprintf("export CARGO_TARGET_%s_LINKER=\"$cc\"", upperTriple))
	}
	if g.opts.CargoOffline {
		cmdParts = append(cmdParts, "export CARGO_NET_OFFLINE=true")
	}

	cargoArgs := fmt.Sprintf("$cargo build --manifest-path %s --target-dir %s --release", manifestPath, targetDir)
	if !isHost && triple != "" {
		cargoArgs += " --target " + triple
	}
	if g.opts.CargoOffline {
		cargoArgs += " --offline"
	}
	cmdParts = append(cmdParts, cargoArgs)
	cmdParts = append(cmdParts, copyCommands...)

	fullCmd := strings.Join(cmdParts, " && ")

	// Inputs
	inputs := srcs
	for _, dep := range dedup(rustlibs) {
		if outs, ok := g.moduleOutputs[dep]; ok {
			inputs = append(inputs, outs...)
		}
	}
	inputs = dedup(inputs)

	if err := g.nw.Build(ninja.BuildEdge{
		Outputs: allOutputs,
		Rule:    "cargo_build",
		Inputs:  inputs,
		Variables: map[string]string{
			"cmd": fullCmd,
		},
	}); err != nil {
		return nil, err
	}

	// Register module outputs
	g.moduleOutputs[mod.Name] = allOutputs
	if crateName != cleanModName {
		g.moduleOutputs["lib"+crateName] = allOutputs
		g.moduleOutputs[crateName] = allOutputs
	}

	_ = g.nw.Build(ninja.BuildEdge{
		Outputs: []string{mod.Name},
		Rule:    "phony",
		Inputs:  allOutputs,
	})

	return allOutputs, nil
}
