// resolveSystemAndroidJar locates system/android.jar containing hidden platform APIs (HwParcel, HwBinder).
func (g *Generator) resolveSystemAndroidJar() string {
	targetApi := g.opts.APILevel
	if targetApi <= 0 {
		targetApi = 34
	}
	candidates := []string{
		filepath.Join(g.opts.TopDir, "prebuilts/sdk", fmt.Sprintf("%d", targetApi), "system/android.jar"),
		filepath.Join(g.opts.TopDir, "prebuilts/sdk/34/system/android.jar"),
		filepath.Join(g.opts.TopDir, "prebuilts/sdk/current/system/android.jar"),
	}
	for _, envVar := range []string{"ANDROID_BUILD_TOP", "LOS_TOP", "TOP"} {
		if v := os.Getenv(envVar); v != "" {
			candidates = append(candidates,
				filepath.Join(v, "prebuilts/sdk", fmt.Sprintf("%d", targetApi), "system/android.jar"),
				filepath.Join(v, "prebuilts/sdk/34/system/android.jar"),
			)
		}
	}
	candidates = append(candidates,
		fmt.Sprintf("/los-21/prebuilts/sdk/%d/system/android.jar", targetApi),
		"/los-21/prebuilts/sdk/34/system/android.jar",
		filepath.Join("/opt/android-sdk/platforms", fmt.Sprintf("android-%d", targetApi), "system/android.jar"),
		filepath.Join("/opt/android-sdk/platforms/android-34/system/android.jar"),
	)
	for _, c := range candidates {
		if fi, err := os.Stat(c); err == nil && !fi.IsDir() {
			return c
		}
	}
	return g.resolveCurrentAndroidJar()
}

// generateHidlJavaLibrary emits the hidl-gen -L java codegen, javac compile, and jar packaging edge.
func (g *Generator) generateHidlJavaLibrary(mod *eval.EvaluatedModule) ([]string, error) {
	fqName := mod.GetString("fq_name")
	if fqName == "" {
		fqName = mod.Name
	}
	jarTarget := filepath.Join(g.libDir(), mod.Name+".jar")
	genDir := filepath.Join(g.opts.OutDir, "gen", mod.Name+"_gen_java")
	classesDir := filepath.Join(g.opts.OutDir, "classes", mod.Name)

	var cpEntries []string
	var cpDeps []string

	androidJar := g.resolveSystemAndroidJar()
	if androidJar != "" {
		cpEntries = append(cpEntries, androidJar)
		cpDeps = append(cpDeps, androidJar)
	}

	for _, dep := range mod.GetStringList("interfaces") {
		depJavaName := sanitizeHidlJavaName(dep)
		depJar := filepath.Join(g.libDir(), depJavaName+".jar")
		cpEntries = append(cpEntries, depJar)
		cpDeps = append(cpDeps, depJar)
	}

	cpFlag := ""
	if len(cpEntries) > 0 {
		cpFlag = "-cp " + strings.Join(dedup(cpEntries), ":")
	}

	halSrcs := g.collectHalSources(mod)
	rootOpt := mod.GetString("root_option")
	if rootOpt == "" {
		rootOpt = g.resolveHidlRootOptions(mod, mod.GetString("root"))
	}

	cpArg := ""
	if cpFlag != "" {
		cpArg = cpFlag + " "
	}

	cmd := fmt.Sprintf("rm -rf %s %s && mkdir -p %s %s && $${HIDL_GEN:-$hidl_gen} -R -p . -o %s -L java %s %s && find %s -name \"*.java\" > %s/java_sources.txt && $javac -encoding UTF-8 -d %s %s@%s/java_sources.txt && $jar cf %s -C %s .",
		genDir, classesDir, genDir, classesDir, genDir, rootOpt, fqName, genDir, genDir, classesDir, cpArg, genDir, jarTarget, classesDir)

	_ = g.nw.Build(ninja.BuildEdge{
		Outputs:   []string{jarTarget},
		Rule:      "hidl_java",
		Inputs:    halSrcs,
		Implicits: dedup(cpDeps),
		Variables: map[string]string{
			"cmd": cmd,
		},
	})

	// Also make jarTarget available under both mod.Name and mod.Name.jar
	g.moduleOutputs[mod.Name+".jar"] = []string{jarTarget}

	return []string{jarTarget}, nil
}

