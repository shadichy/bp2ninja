package generator

import (
	"fmt"
	"io"
	"strings"
)

// WriteSisoConfig writes a companion Starlark config for executing the
// generated build graph with siso (https://go.chromium.org/build/siso), the
// drop-in Ninja replacement with native REAPI/RBE support.
//
// The ninja file itself already carries siso rule bindings (restat_content,
// sandbox_disabled and, with -siso-remote, remote_enabled on pure compile
// actions). This config adds per-step rules that cannot be expressed as ninja
// bindings: keeping link/archive outputs on local disk and optional toolchain
// / sysroot input hooks for remote execution (e.g. extracted APEX payloads
// under /apex/<pkg>/include).
//
// Install next to the build directory and run:
//
//	mkdir -p build/config/siso && cp siso.star build/config/siso/main.star
//	siso ninja -C .
func (g *Generator) WriteSisoConfig(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Generated by bp2ninja -siso\n")
	b.WriteString("# Companion Starlark config for the emitted build.ninja (siso >= v1.6).\n")
	b.WriteString("#\n")
	b.WriteString("# Install and run with siso instead of ninja:\n")
	b.WriteString("#   mkdir -p build/config/siso && cp siso.star build/config/siso/main.star\n")
	b.WriteString("#   siso ninja -C .\n")
	b.WriteString("#\n")
	b.WriteString("# The ninja file already carries siso rule bindings (restat_content,\n")
	b.WriteString("# sandbox_disabled and, with -siso-remote, remote_enabled on compile\n")
	b.WriteString("# actions). This config holds per-step rules that cannot be expressed\n")
	b.WriteString("# as ninja bindings.\n")
	b.WriteString("#\n")
	b.WriteString("# Reference: https://chromium.googlesource.com/build/+/main/siso/docs/starlark_config.md\n\n")

	b.WriteString("load(\"@builtin//encoding.star\", \"json\")\n")
	b.WriteString("load(\"@builtin//struct.star\", \"module\")\n\n")

	b.WriteString("def init(ctx):\n")
	b.WriteString("  step_config = {\n")
	b.WriteString("    \"rules\": [\n")
	b.WriteString("      # Compile actions build against sysroots outside the workspace\n")
	b.WriteString("      # (NDK, host glibc, extracted APEX payloads), so their depfiles\n")
	b.WriteString("      # legitimately contain absolute paths to system headers.\n")
	b.WriteString("      {\n")
	b.WriteString("        \"name\": \"compile-abs-sysroot\",\n")
	b.WriteString("        \"action\": \"^(cc_compile|cxx_compile|as_compile)$\",\n")
	b.WriteString("        \"input_root_absolute_path\": True,\n")
	b.WriteString("      },\n")
	b.WriteString("      # Link / archive steps consume prebuilt libraries outside the\n")
	b.WriteString("      # workspace, so keep their outputs on local disk.\n")
	b.WriteString("      {\n")
	b.WriteString("        \"name\": \"link-local\",\n")
	b.WriteString("        \"action\": \"^(link_shared|link_binary|partial_link|archive_static|ar_mri)$\",\n")
	b.WriteString("        \"output_local\": True,\n")
	b.WriteString("      },\n")
	b.WriteString("    ],\n")
	b.WriteString("  }\n")
	b.WriteString("  return module(\n")
	b.WriteString("    \"bp2ninja\",\n")
	b.WriteString("    step_config = json.encode(step_config),\n")
	b.WriteString("    filegroups = {},\n")
	b.WriteString("    handlers = {},\n")
	b.WriteString("  )\n\n")

	b.WriteString("# Toolchain / sysroot input hooks for remote execution (uncomment and\n")
	b.WriteString("# extend when running against a REAPI backend). Rules add inputs to\n")
	b.WriteString("# every step whose command starts with command_prefix:\n")
	if toolDir := g.toolchainBinDirHint(); toolDir != "" {
		fmt.Fprintf(&b, "# {\"name\": \"toolchain-inputs\", \"command_prefix\": %q,\n", toolDir+"/")
		if sys := g.sysrootHint(); sys != "" {
			fmt.Fprintf(&b, "#  \"inputs\": [%q]},\n", sys)
		} else {
			b.WriteString("#  \"inputs\": [...]},\n")
		}
	}
	b.WriteString("# APEX dev sysroots, one entry per consumed sysroot:\n")
	b.WriteString("# {\"name\": \"apex-sysroot-inputs\", \"command_prefix\": \"clang\",\n")
	b.WriteString("#  \"inputs\": [\"/apex/com.android.art/include\"]},\n")

	_, err := io.WriteString(w, b.String())
	return err
}

// toolchainBinDirHint reports the NDK prebuilt bin directory used by the
// emitted $cc / $cxx / $ar variables, if resolvable from the options.
func (g *Generator) toolchainBinDirHint() string {
	for _, tool := range []string{g.opts.ClangPath, g.opts.ClangCxxPath, g.opts.ArPath} {
		if tool == "" {
			continue
		}
		if i := strings.LastIndex(tool, "/bin/"); i > 0 {
			return tool[:i+len("/bin")]
		}
	}
	if g.opts.NDKDir != "" {
		return g.opts.NDKDir + "/toolchains/llvm/prebuilt"
	}
	return ""
}

// sysrootHint reports the sysroot path the emitted graph compiles against.
func (g *Generator) sysrootHint() string {
	if g.opts.SysrootDir != "" {
		return g.opts.SysrootDir
	}
	if g.opts.NDKDir != "" {
		return g.opts.NDKDir + "/toolchains/llvm/prebuilt/linux-x86_64/sysroot"
	}
	return ""
}
